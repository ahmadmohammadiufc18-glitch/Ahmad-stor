-- Ahmad Stor production schema
-- Prices are stored/displayed in TOMAN. Zarinpal API receives RIAL (toman * 10).
create extension if not exists pgcrypto;

create table if not exists public.products (
  id bigint generated by default as identity primary key,
  slug text unique not null,
  name text not null,
  description text not null default '',
  category text not null default 'device',
  price_toman bigint not null check (price_toman >= 0),
  image_url text,
  active boolean not null default true,
  stock integer not null default 0 check (stock >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  phone text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id),
  status text not null default 'pending_payment'
    check (status in ('pending_payment','paid','payment_failed','cancelled','processing','shipped','completed','refunded')),
  currency text not null default 'IRR' check (currency = 'IRR'),
  subtotal_toman bigint not null check (subtotal_toman > 0),
  total_toman bigint not null check (total_toman > 0),
  customer_name text not null,
  customer_phone text not null,
  shipping_address text not null,
  payment_provider text not null default 'zarinpal',
  payment_authority text unique,
  payment_ref_id text,
  paid_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated always as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null,
  unit_price_toman bigint not null check (unit_price_toman >= 0),
  quantity integer not null check (quantity between 1 and 20),
  line_total_toman bigint not null check (line_total_toman >= 0)
);

create index if not exists orders_user_created_idx on public.orders(user_id, created_at desc);
create index if not exists order_items_order_idx on public.order_items(order_id);
create index if not exists products_active_idx on public.products(active, category);

alter table public.products enable row level security;
alter table public.profiles enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;

drop policy if exists "Anyone can view active products" on public.products;
create policy "Anyone can view active products" on public.products for select using (active = true);
drop policy if exists "Users can read own profile" on public.profiles;
create policy "Users can read own profile" on public.profiles for select to authenticated using (auth.uid() = id);
drop policy if exists "Users can create own profile" on public.profiles;
create policy "Users can create own profile" on public.profiles for insert to authenticated with check (auth.uid() = id);
drop policy if exists "Users can update own profile" on public.profiles;
create policy "Users can update own profile" on public.profiles for update to authenticated using (auth.uid() = id) with check (auth.uid() = id);
drop policy if exists "Users can read own orders" on public.orders;
create policy "Users can read own orders" on public.orders for select to authenticated using (auth.uid() = user_id);
drop policy if exists "Users can read own order items" on public.order_items;
create policy "Users can read own order items" on public.order_items for select to authenticated using (
  exists (select 1 from public.orders o where o.id = order_id and o.user_id = auth.uid())
);

-- Do not grant clients insert/update/delete access to orders, order_items, or products.
-- Only trusted server-side Edge Functions using the service role can create/verify payments or mutate stock.
